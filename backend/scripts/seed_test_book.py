# ───────────────────────── 生成逻辑 ─────────────────────────


def pick(pool: list[str], n: int, salt: int) -> str:
    """按章节号确定性地从模板池选一个变体。"""
    return pool[(n - 1) * salt % len(pool)]


def enrich_iter(n: int):
    """按章节号确定性产出铺陈段索引；只产出该章节之前已出场的设定，
    同一章内不重复（循环复用保证有解）。"""
    eligible = [i for i, (min_ch, _) in enumerate(ENRICHMENT) if min_ch <= n]
    used: set[int] = set()
    k = 0
    while True:
        if len(used) >= len(eligible):
            used.clear()  # 允许复用，避免死循环
        idx = eligible[(n * 17 + k * 31) % len(eligible)]
        if idx in used:
            k += 1
            continue
        used.add(idx)
        yield idx
        k += 1


def merge_fragments(fragments: list[str], min_para_len: int = 430, max_paras: int = 8) -> list[str]:
    """把短叙事碎片合并为 5-10 个自然段（每段 ~430+ 字，共约 3000 字）。"""
    merged: list[str] = []
    cur = ""
    for frag in fragments:
        if cur and len(cur) >= min_para_len and len(merged) + 1 < max_paras:
            merged.append(cur)
            cur = frag
        else:
            cur += frag
    if cur:
        merged.append(cur)
    return merged


def build_chapter(n: int) -> str:
    """生成第 n 章的完整正文（合并为 5-10 个自然段，用空行分隔）。"""
    loc, mood, stage, keyword = CHAPTER_CONTEXT[n - 1]
    ctx = {
        "bookstore": BOOKSTORE,
        "loc": loc,
        "mood": mood,
        "stage": stage,
        "keyword": keyword,
    }

    opening = pick(OPENINGS, n, 7).format(**ctx)
    cores = list(CHAPTER_CORES[n])
    if n == CHAPTER_COUNT:
        # 终章：不用通用过渡/悬念结尾，改用收束式结局
        trans = ""
        refl = ""
        close = (
            "夜里，苏晚来铺子喝茶，小满也难得从雾里钻出来，蹲在门槛上啃一块桂花糕。"
            "爷爷在老周那儿下棋，输了棋也不肯认。林默站在灯下，看着这一屋子的人，"
            "忽然觉得，这就是他这一路走来换来的东西。他把钥匙挂回门框内侧，吹灭灯，"
            "听见雾城的方向传来一声悠长的钟鸣，像是这座城轻轻说了一声：晚安。"
        )
    else:
        trans = pick(TRANSITIONS, n, 3).format(**ctx)
        refl = pick(REFLECTIONS, n, 7).format(**ctx)
        close = pick(CLOSINGS, n, 11).format(**ctx)

    # 1. 先预演：确定需要多少段铺陈才能把字数补到 [MIN_LEN, MAX_LEN]
    base_total = len(opening) + sum(len(c) for c in cores) + len(trans) + len(refl) + len(close)
    e_iter = enrich_iter(n)
    chosen: list[str] = []
    total = base_total
    while total < MIN_LEN:
        e = ENRICHMENT[next(e_iter)][1]
        chosen.append(e)
        total += len(e)
    # 若超长，逆序移除最后补入的铺陈段
    while total > MAX_LEN and chosen:
        total -= len(chosen.pop())
    # 若仍超长（单段铺陈也过长），按句子边界裁剪最后一段铺陈
    if total > MAX_LEN and chosen:
        need = total - MAX_LEN
        last = chosen[-1]
        cut = len(last) - need
        while cut > 0 and last[cut - 1] not in "。！？":
            cut -= 1
        if cut <= 0:
            cut = len(last) - need
        chosen[-1] = last[:cut].rstrip() + "……"
        total = base_total + sum(len(c) for c in chosen)

    # 2. 构造叙事节拍：开头 → 核心段（每个核心段后轮流穿插铺陈）→ 过渡 → 心理 → 结尾
    beats: list[str] = [opening]
    anchors: list[int] = []  # 当前 beats 中「每个核心段之后」的插入锚点
    for core in cores:
        beats.append(core)
        anchors.append(len(beats))
    if n == CHAPTER_COUNT and chosen:
        # 终章：结局段之后不再穿插铺陈，保证收束结局落在章尾
        anchors = anchors[:-1]
    if trans:
        beats.append(trans)
    if refl:
        beats.append(refl)
    beats.append(close)

    for k, e in enumerate(chosen):
        pos = anchors[k % len(anchors)]
        beats.insert(pos, e)
        for ai, a in enumerate(anchors):
            if a >= pos:
                anchors[ai] = a + 1

    # 3. 合并为自然段
    paragraphs = merge_fragments(beats)
    return "\n\n".join(paragraphs)


def build_book() -> list[dict]:
    """生成全部章节，输出 create_novel_record 所需的章节字典。"""
    chapters: list[dict] = []
    for n in range(1, CHAPTER_COUNT + 1):
        content = build_chapter(n)
        chapters.append(
            {
                "chapter_number": n,
                "title": CHAPTER_TITLES[n - 1],
                "content": content,
                "word_count": len(content),
            }
        )
    return chapters


