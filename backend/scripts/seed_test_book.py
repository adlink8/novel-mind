async def main() -> None:
    chapters = build_book()

    print("=" * 60)
    print(f"《{TITLE}》生成完成，共 {len(chapters)} 章")
    print("=" * 60)
    for ch in chapters:
        flag = ""
        if ch["word_count"] < MIN_LEN:
            flag = "  <-- 低于下限!"
        elif ch["word_count"] > MAX_LEN:
            flag = "  <-- 超出上限!"
        print(f"  {ch['chapter_number']:>2} {ch['title']:<12} {ch['word_count']} 字{flag}")

    total_words = sum(ch["word_count"] for ch in chapters)
    print("-" * 60)
    print(f"总字数: {total_words} (目标 ≈{CHAPTER_COUNT * 3000})")

    if any(ch["word_count"] < MIN_LEN or ch["word_count"] > MAX_LEN for ch in chapters):
        raise SystemExit("存在章节字数不在 2800–3200 区间，请检查生成逻辑后重跑。")

    async with async_session_factory() as db:
        novel = await novel_service.create_novel_record(
            db,
            title=TITLE,
            chapters=chapters,
            author=AUTHOR,
            owner_id=OWNER_ID,
        )
        await db.commit()

        print("-" * 60)
        print(f"写入成功: novel id={novel.id} title={novel.title}")
        print(f"  chapter_count = {novel.chapter_count}")
        print(f"  word_count    = {novel.word_count}")
        print(f"  status        = {novel.status}")
        print(f"  owner_id      = {novel.owner_id}")

        # ── 内置验证查询 ──
        db_count = await db.scalar(
            select(func.count()).select_from(Chapter).where(Chapter.novel_id == novel.id)
        )
        print("-" * 60)
        print("内置验证:")
        print(f"  chapters 表中该 novel 的行数 = {db_count}")
        for sample_no in (1, 15, 30):
            ch = await db.scalar(
                select(Chapter)
                .options(undefer(Chapter.content))
                .where(
                    Chapter.novel_id == novel.id,
                    Chapter.chapter_number == sample_no,
                )
            )
            if ch:
                print(
                    f"  抽样 第{sample_no}章「{ch.title}」 content 长度 = {len(ch.content) if ch.content else 0}"
                )
            else:
                print(f"  抽样 第{sample_no}章 未找到!")


if __name__ == "__main__":
    asyncio.run(main())
